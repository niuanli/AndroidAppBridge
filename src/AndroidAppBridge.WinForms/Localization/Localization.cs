    // Translate longer messages first so shorter fragments cannot break a complete sentence match.
    static readonly KeyValuePair<string, string>[] Sorted = Terms.OrderByDescending(p => p.Key.Length).ToArray();
    public static string Text(string text, bool english)
    {
        if (!english)
            return text;
        foreach (var p in Sorted)
            text = text.Replace(p.Key, p.Value, StringComparison.Ordinal);
        return text;
    }
